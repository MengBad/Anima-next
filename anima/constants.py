"""公共常量 —— 避免多处重复定义导致不一致。"""

import re

# OneBot/CQ 传输格式正则：匹配所有已知 CQ 类型（含未闭合的尾部 `]?`）。
# 用于出站清理、记忆落盘清洗等场景，确保所有模块使用同一份定义。
#
# ⚠️ 枚举纪律（2026-09-21 教训）：类型清单必须**按实际会入站的段枚举**，
# 漏一个就会把 CQ 码原样漏进 LLM 上下文与向量记忆。本次补的是 `reply` ——
# 「答非所问」事故里，带引用回复的消息 raw_message 含 `[CQ:reply,id=…]`，
# 而旧表独缺该类型 ⇒ 残留进 ctx.text（audit text_length=3 vs ReAct text_len=28，
# 差的 25 字就是它）。同时补齐 `json/xml/forward/node/file/markdown` ——
# `channels/onebot11.py` 的 rich_blocks 证明这些段确实会入站。
# 1 处定义、5 处消费（`_shared._clean_transport_text`、`chat_memory` 两处、`autonomy`、
# `event_text`）。
CQ_TRANSPORT_RE = re.compile(
    r"\[CQ:(?:image|face|bface|sface|record|video|poke|share|music|location|at"
    r"|reply|json|xml|forward|node|file|markdown)[^\]]*\]?",
    re.I,
)


# ---------------------------------------------------------------------------
# 「事件正文」唯一口径
# ---------------------------------------------------------------------------
# 背景（2026-09-25 出入站审核定案）：一个入站事件里有两个文本字段，**含义不同**：
#   * `event["text"]`         —— 渠道层拼好的**正文**（text 段拼接 + 富媒体摘要，
#                                `channels/onebot11.py:361/:392`），**不含 CQ 码**。
#   * `event["message"]`      —— `raw_message` 的**传输原文**（`:336` 只设 message、
#                                **从不设 `raw_message`**）⇒ 含 `[CQ:json,…]` 之类。
# 全仓库其它消费点（prefilter/attachment 阶段回写、`pilot/message_adapter`、
# `group_gate` 的 I6 注释）都按「`event["text"]` 是正文」这一假设写的。
# 🔴 而 `llm/handler.py` 的私聊合并 / 群防抖两条路径此前取
#    `raw_message or message` ⇒ **必落到 CQ 原文**（`raw_message` 恒缺）⇒
#    卡片/引用类消息被 `CQ_TRANSPORT_RE` 整段剥空 ⇒ `memory.py` 判空 `SKIP_REPLY`
#    （静默丢弃：无日志/无计数/无出站，09-24 14:18:17 私聊实证），同一个变量还把
#    CQ 码写进了 stickers/关系/情节等持久记忆（1,056 处残留）。
# ⇒ **凡取正文一律走本函数**，别在别处再写第二份 `or` 链。
def event_text(event: "dict | None") -> str:
    """取事件的**对话正文**：`text` 优先，缺失时才回落传输原文。"""
    if not event:
        return ""
    return str(event.get("text") or event.get("raw_message") or event.get("message") or "")

# ---------------------------------------------------------------------------
# 承诺（commitment）判别 —— **唯一口径**，勿在别处再写第二份
# ---------------------------------------------------------------------------
# 背景（2026-09-20 深浅两轮出站审计）：pipeline 的 `_PROMISE_RE` 与
# `memory/episodes.py` 的 `_COMMITMENT_HINT` 各自实现了一份"承诺检测"，
# 而**两边都吃裸时间词**（下次 / 明天 / 今晚 / 到时候 / 等下…）。后果是：
#   「下次再乱喵，本喵真拿尾巴抽你了」   —— 玩笑，被记成"bot 答应了某事"
#   「别踩电源键喵…今晚就别想睡了」       —— 闲聊，被记成承诺
#   「等下，你怎么也抢本喵的自称啊」      —— 斗嘴，被记成承诺
# 再由主动发言沿着假承诺去"跟进"一件根本不存在的事 ⇒ 用户侧读起来就是
# "bot 完全不理解刚才在说什么"。生产实测：commitments.json **14/14 全是假账**；
# agenda.json 33 条里 11 条 promise_followup 同源。
#
# 判据（收紧方向 = **宁可漏记，不可编造**）：
#   ① 明确的第一人称承诺短语 —— 自带动作，无需时间词；
#      ⚠️ 但 `会` **必须**后接一个"为某人做某事"的动作才成立：`会` 单独出现只是
#         "会做某事"的**能力陈述**（「本喵会的本事可多着呢」「还好我会功夫」），
#         二次回测（用三本账全量原文跑词表）证明这类句子**仍会被旧版①误判**，
#         故改为 `(?:我|本喵|哈基米)会(?![不的])` + 12 字内必须出现动作词。
#      同理 `约好` 排除 autonomy 自己插的标签「（约好 …）」，`说好` 排除话语标记「先说好」。
#   ② 时间词**必须**与「为某人做某事」的标志词同现（同一小句内、间隔 ≤14 字）。
#      ⚠️ 裸时间词单独出现**不构成承诺** —— 这是本次修复的核心。
_PROMISE_ACT = (
    r"(?:帮你|帮本喵|帮你查|帮你看|帮你盯|帮你找|帮你问|帮你试|我给你|给你|替你|"
    r"发你|发给你|发出来|发出去|告诉你|提醒你|提醒我|带你|教你|"
    r"去查|查一下|去看看|看着|盯着|去问|去找|去搜|搞定|处理|"
    r"记下|记住|记着|来接你|来找你)"
)
COMMITMENT_RE = re.compile(
    r"(?:"
    # ① 第一人称承诺短语：**代词 + 承诺动词核**（会/帮/来/记得），且必须后接动作词。
    #   ⚠️ 动词核一律不得裸用 —— 名词化/否定/话题结构陷阱对每个动词都成立：
    #     `会`   「本喵会的本事」     = 能力陈述（会做某事 ≠ 会去做某事）
    #     `帮`   「本喵帮不了你」     = **拒绝**（语义正好相反）
    #     `来`   「天天本喵来本喵去」 = 话题结构（不是"我来做某事"）
    #     `记得` 「本喵记得你说过」   = 陈述记忆（不是承诺）
    #   `(?![不的])` 挡否定与名词化，`(?=…)` 要求 12 字内出现 `_PROMISE_ACT`。
    #   🔴 2026-09-21 第三轮：前两轮只收了 `会`，`帮/来/记得` 仍是裸词 ⇒ "修好"后
    #   23h 内又被 `本喵来` 造出 1 条假债，8.5h 后兑现成一次答非所问的主动追问。
    #   教训：收紧一个裸词必须把**同类词全部枚举**（`本喵X` 动词系列），否则只是
    #   把同一个坑挪到下一个词上。用词表原文回测时须扫**出站正文**，不是记忆摘要。
    r"(?:我|本喵|哈基米)(?:会|帮|来|记得)(?![不的])"
    r"(?=[^。！？!?\n]{0,12}" + _PROMISE_ACT + r")|"
    r"我帮你|我来帮你|本喵去查|"
    r"答应你|(?<![（(])约好|(?<!先)说好|别忘了|记得帮|记得提醒|记得叫|提醒我|"
    r"回头帮你|待会儿帮你|待会帮你|稍后帮你|下次帮你|下次再帮|回头再帮|"
    r"帮你查|帮你看|帮你盯|帮你看看|帮你问问|帮你找找|帮你试试|"
    r"本喵记下|本喵记住|记下了|记住了|到时候告诉"
    # ② 时间词 + 承诺动作（间隔 ≤14 字，且不得跨句号/叹问号）
    r"|(?:明天|明日|后天|今晚|今天晚|稍后|待会|待会儿|过会儿|回头|下次|"
    r"到时候|等下|一会儿|这就)"
    r"[^。！？!?\n]{0,14}"
    r"(?:帮你|帮本喵|给你|替你|发你|发给你|告诉你|提醒你|提醒我|带你|教你|给你看|"
    r"去查|去看看|去问|去找|去搜|帮你查|帮你看|帮你盯|帮你找|帮你问|帮你试)"
    r")",
    re.I,
)


# ── 否定守卫（2026-10-18，D-35）──────────────────────────────────────────────
# 🔴 生产实证（这次是**假账**，不是话术）：
#   bot 出站「…本喵才不**帮你看**什么脑洞学生会呢，要看你自己看去喵！」
#   被 `COMMITMENT_RE` 的**裸多字短语分支**（`帮你查|帮你看|帮你盯|…`）命中
#   ⇒ 判成承诺 ⇒ 建债 `content/due_hint`=整句 ⇒ 建 2 条议程（promise_followup +
#   debt_due，`text_intent`=「之前答应了 X 一件事…当时的回复是：<这句拒绝>」）
#   ⇒ T+6h 议程到期，主动发言把「当时回复的是拒绝」喂回模型
#   ⇒ 模型把"没帮"改写成"帮了"（06:32「勉为其难帮你瞅了一眼」）并沿用旧句式
#   ⇒ 新句再被同一分支判成承诺。**一句拒绝 → 13 假债 → 26 议程**（生产实测）。
#
# 根因形状与 09-21 那次完全相同：那轮发现「`帮/来/记得` 不得裸用」，
# 于是给 **代词+动词核** 分支加了 `(?![不的])`，却**漏了多字短语分支**
# （`帮你看` 前面紧邻的通常正是"不"）⇒ 同一个坑挪到了隔壁。
# 这次不靠"再加一个字符类"（lookbehind 定宽，组合会爆炸），改用**匹配后判定**：
# 看命中位置的**同一句内**前缀，若 ≤4 字内出现否定词，则该命中作废。
_NEGATION_MARKERS = (
    "才不", "不会", "不想", "不用", "不必", "不", "别", "没", "甭",
    "懒得", "拒绝", "绝不", "从不", "休想", "妄想",
)
#: 命中点之前、同一句内允许的最大间隔（超过则不属于"否定这句承诺"）
_NEG_LOOKBACK_CHARS = 6

#: 真正贴住动词的否定形态：可选副词 + 否定词 + 可选情态字，且必须**紧邻命中点**。
#: 🔴 不能只做"前 6 字里出现否定词"——「别急，我等下再帮你查」里的「别」是在
#:    安抚对方，不是否定承诺；放宽会把这句真承诺判成拒绝（首版实测漏判 1/6）。
_NEG_ADJACENT_RE = re.compile(
    r"(?:懒得|拒绝|休想|妄想|绝不|从不)$"
    r"|(?:[才就也都还又])?(?:不|别|没|甭)(?:太)?[会想用必得]?$"
)


#: 落在**命中区间内部**的否定（时间词分支允许中间夹 ≤14 字，
#: 「今晚休想让本喵帮你踩背」的「休想」离动词 5 字，紧邻判定看不到）。
_NEG_IN_SPAN_RE = re.compile(r"休想|妄想|别想|做梦|才不|不会|不想|懒得|凭什么|少来")


def _sent_prefix(text: str, pos: int) -> str:
    """取 `pos` 之前、**同一句内**的前缀（遇句末标点截断）。"""
    cut = -1
    for i in range(pos - 1, -1, -1):
        if text[i] in "。！？!?\n":
            cut = i
            break
    return text[cut + 1:pos]


def _negated_at(text: str, pos: int) -> bool:
    """命中点**紧邻处**是否有否定（≤4 字内且必须贴在动词前）。"""
    head = _sent_prefix(text, pos)
    if not head:
        return False
    tail = head[-4:]
    if _NEG_ADJACENT_RE.search(tail):
        return True
    return any(mark in tail for mark in ("懒得", "拒绝", "休想", "妄想", "绝不", "从不"))


def commitment_match(text: str):
    """返回**第一个未被否定**的承诺命中（`re.Match`），无则 `None`。

    所有消费者都应改用它而不是 `COMMITMENT_RE.search()` —— 后者会把
    「本喵才不帮你看」这种**语义相反的拒绝**当成承诺记账。
    """
    for m in COMMITMENT_RE.finditer(text or ""):
        if _negated_at(text, m.start()):
            continue
        # 第二道：否定词可能落在**命中区间内部**（时间词分支允许中间夹 ≤14 字）：
        #   「今晚**休想**让本喵帮你踩背暖床」——否定在动词前 5 字，紧邻判定看不到。
        # 生产实证：这类句子进了 debts（"休想…帮你踩背"被记成承诺）。
        if _NEG_IN_SPAN_RE.search(m.group(0)):
            continue
        return m
    return None


def is_commitment(text: str) -> bool:
    """`commitment_match` 的布尔壳（供只需要"有没有"的调用点用）。"""
    return commitment_match(text) is not None
